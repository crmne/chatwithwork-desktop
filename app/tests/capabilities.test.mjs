// A stale generated permission can hide a removed command in a local build.
// Check the source declarations, so a clean release build sees the same set.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, readdirSync } from "node:fs";

test("bundled capabilities name only commands generated by the build", () => {
  const build = readFileSync(new URL("../build.rs", import.meta.url), "utf8");
  const commands = new Set([...build.matchAll(/^\s+"(\w+)",$/gm)].map((match) => match[1].replaceAll("_", "-")));
  assert.ok(commands.size > 0);
  const directory = new URL("../capabilities/", import.meta.url);
  for (const file of readdirSync(directory).filter((name) => name.endsWith(".json"))) {
    const capability = JSON.parse(readFileSync(new URL(file, directory), "utf8"));
    for (const permission of capability.permissions) {
      const name = typeof permission === "string" ? permission : permission.identifier;
      if (!name.includes(":")) {
        assert.ok(commands.has(name.replace(/^(allow|deny)-/, "")), `${file}: ${name} has no command`);
      }
    }
  }
});
